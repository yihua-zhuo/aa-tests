export type ResourceDef = {
  key: string;
  table: string;
  tag: string;
  description: string;
  scope: ScopeKind;
  write: WriteMode;
  columns: string[];
  json?: string[];
  bool?: string[];
  versioned?: boolean;
  created?: boolean;
  updated?: boolean;
  order?: string;
  search?: string[];
  create?: z.ZodType;
  update?: z.ZodType;
  allowCreate?: boolean;
  allowUpdate?: boolean;
  allowDelete?: boolean;
  /** Composite-key or otherwise unsupported tables use dedicated endpoints. */
  generic?: boolean;
};

function updateOf(create: z.ZodType): z.ZodType {
  const candidate = create as unknown as { partial?: () => z.ZodObject };
  if (typeof candidate.partial === 'function') {
    try {
      return (candidate.partial() as z.ZodObject).extend({
        version: z.number().int().min(1),
      });
    } catch {
      // Schemas with refinements cannot be partially applied; fall back to a
      // permissive body and let the table's column whitelist constrain writes.
    }
  }
  return z.object({ version: z.number().int().min(1) }).passthrough();
}

function def(definition: ResourceDef): ResourceDef {
  return {
    ...definition,
    allowCreate: definition.allowCreate ?? Boolean(definition.create),
    allowUpdate: definition.allowUpdate ?? Boolean(definition.create),
    allowDelete: definition.allowDelete ?? false,
    generic: definition.generic ?? true,
  };
}

